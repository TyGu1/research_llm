def _fmt_questions(questions: list[str]) -> str:
    return "\n".join(f"- {q}" for q in questions)


def _first_json(text: str) -> dict | None:
    m = re.search(r"\{.*\}", text, flags=re.DOTALL)
    if not m:
        return None
    blob = m.group(0)
    try:
        return json.loads(blob)
    except json.JSONDecodeError:
        # tolerate trailing commas / single quotes
        blob2 = re.sub(r",\s*([}\]])", r"\1", blob)
        try:
            return json.loads(blob2)
        except json.JSONDecodeError:
            return None


def _json_reconstruction(raw: str) -> tuple[str, dict]:
    data = _first_json(raw)
    if not data or not isinstance(data, dict):
        return raw, {"parsed": False}
    rec = data.get("reconstruction", "")
    if not isinstance(rec, str):
        rec = json.dumps(rec)
    extra = {k: v for k, v in data.items() if k != "reconstruction"}
    extra["parsed"] = True
    # Make the whole output count for substring metrics (category guesses, topic words are leakage too).
    full = rec + "\n" + " ".join(str(v) for v in extra.values())
    return full, extra


class LLMAttacker:
    def __init__(self, client, max_tokens: int = 700, temperature: float = 0.0):
        self._client = client
        self._max_tokens = max_tokens
        self._temperature = temperature

    def _gen(self, prompt: str, system: str, max_tokens: int | None = None) -> str:
        kwargs = {}
        if max_tokens is not None:
            kwargs["max_tokens"] = max_tokens
        try:
            return self._client.generate(prompt, system=system, temperature=self._temperature, **kwargs)
        except TypeError:
            # mock clients without max_tokens
            return self._client.generate(prompt, system=system, temperature=self._temperature)

    # ── rung a ──────────────────────────────────────────────────────────────
    def direct(self, questions: list[str]) -> AttackOutput:
        p = DIRECT_PROMPT.format(questions=_fmt_questions(questions))
        return AttackOutput("direct", "Q", self._gen(p, DIRECT_SYSTEM), prompt_chars=len(p))

    def expert(self, questions: list[str]) -> AttackOutput:
        p = EXPERT_PROMPT.format(questions=_fmt_questions(questions))
        return AttackOutput("expert", "Q", self._gen(p, EXPERT_SYSTEM), prompt_chars=len(p))

    def icl(self, questions: list[str], examples: list[ICLExample], name: str) -> AttackOutput:
        ex = "\n\n".join(
            ICL_EXAMPLE.format(
                i=i + 1,
                questions=_fmt_questions(e.questions),
                original=e.original_question,
                gold="; ".join(f'"{g[:120]}"' for g in e.gold),
                excerpt=e.context_excerpt[:300].replace("\n", " "),
            )
            for i, e in enumerate(examples)
        )
        p = ICL_PROMPT.format(k=len(examples), examples=ex, questions=_fmt_questions(questions))
        return AttackOutput(name, "Q", self._gen(p, ICL_SYSTEM), extra={"k": len(examples)}, prompt_chars=len(p))

    # ── rung b ──────────────────────────────────────────────────────────────
    def category_inversion(self, questions: list[str]) -> AttackOutput:
        p = CATEGORY_PROMPT.format(
            n=len(ALL_CATEGORIES),
            categories="\n".join(f"- {c}" for c in ALL_CATEGORIES),
            questions=_fmt_questions(questions),
        )
        raw = self._gen(p, CATEGORY_SYSTEM)
        rec, extra = _json_reconstruction(raw)
        cats = extra.get("categories") if isinstance(extra.get("categories"), list) else []
        extra["categories_norm"] = [normalise_category_guess(str(c)) for c in cats]
        return AttackOutput("category_inversion", "Q+", rec, extra=extra, prompt_chars=len(p))

    def absence_q(self, questions: list[str], topics: TopicDistribution | None) -> AttackOutput:
        p = ABSENCE_Q_PROMPT.format(questions=_fmt_questions(questions))
        raw = self._gen(p, ABSENCE_Q_SYSTEM)
        rec, extra = _json_reconstruction(raw)
        extra.update(_excluded_word_scores(extra.get("excluded_words"), topics))
        return AttackOutput("absence_q", "Q+", rec, extra=extra, prompt_chars=len(p))

    def absence_s0(self, s0_text_excluded: str, topics: TopicDistribution | None) -> AttackOutput:
        topics_str = json.dumps(topics.topics) if topics else "{}"
        p = ABSENCE_S0_PROMPT.format(topics=topics_str, s0_text=s0_text_excluded)
        raw = self._gen(p, ABSENCE_S0_SYSTEM)
        rec, extra = _json_reconstruction(raw)
        extra.update(_excluded_word_scores(extra.get("excluded_words"), topics))
        return AttackOutput("absence_s0", "S0", rec, extra=extra, prompt_chars=len(p))

    # ── rung c ──────────────────────────────────────────────────────────────
    def multi_query(self, question_sets: list[list[str]]) -> AttackOutput:
        sets = "\n\n".join(f"Set {i + 1}:\n{_fmt_questions(qs)}" for i, qs in enumerate(question_sets))
        p = MULTI_PROMPT.format(k=len(question_sets), sets=sets)
        return AttackOutput("multi_query", "Qxk", self._gen(p, MULTI_SYSTEM, max_tokens=900),
                            extra={"k": len(question_sets)}, prompt_chars=len(p))

    # ── baseline arms ───────────────────────────────────────────────────────
    def dp_direct(self, sanitized_text: str, observation: str = "DP-text") -> AttackOutput:
        p = DP_DIRECT_PROMPT.format(text=sanitized_text)
        return AttackOutput("dp_direct", observation, self._gen(p, DP_SYSTEM, max_tokens=1000), prompt_chars=len(p))

    def dp_icl(self, sanitized_text: str, examples: list[tuple[str, str]], observation: str = "DP-text") -> AttackOutput:
        ex = "\n\n".join(
            DP_EXAMPLE.format(i=i + 1, sanitized=s[:700].replace("\n", " "), original=o[:700].replace("\n", " "))
            for i, (s, o) in enumerate(examples)
        )
        p = DP_ICL_PROMPT.format(k=len(examples), examples=ex, text=sanitized_text)
        return AttackOutput("dp_icl", observation, self._gen(p, DP_SYSTEM, max_tokens=1000),
                            extra={"k": len(examples)}, prompt_chars=len(p))

    def sub_direct(self, substituted_text: str) -> AttackOutput:
        p = SUB_DIRECT_PROMPT.format(text=substituted_text)
        return AttackOutput("sub_direct", "SUB-text", self._gen(p, SUB_SYSTEM, max_tokens=1000), prompt_chars=len(p))


def _excluded_word_scores(guessed, topics: TopicDistribution | None) -> dict:
    """Precision/recall of the guessed excluded-word set against the real exclusion set."""
    if topics is None:
        return {}
    truth = _topic_vocab_words(topics)
    if not isinstance(guessed, list):
        return {"excl_truth_n": len(truth), "excl_recall": 0.0, "excl_precision": 0.0}
    g = {re.sub(r"[^a-z0-9\-]", "", str(w).lower()) for w in guessed}
    g.discard("")
    hits = truth & g
    return {
        "excl_truth_n": len(truth),
        "excl_guess_n": len(g),
        "excl_recall": (len(hits) / len(truth)) if truth else 0.0,
        "excl_precision": (len(hits) / len(g)) if g else 0.0,
    }
