"""
LLM-driven reconstruction attacks.

Rung a  — single-query: direct, expert (paper prompts, verbatim), ICL-k, ICL-same.
Rung b1 — pipeline-aware category inversion (Q+): pick the CUAD category, then reconstruct.
Rung b2 — absence fingerprint: on Q only (realistic, Q+) and on the S0 text (upper bound).
Rung c  — multi-query aggregation (Qxk).
Baseline arms — DP / substitution text reconstruction (direct and ICL, Pang et al. recipe).

Every attack returns an AttackOutput that records its observation set.
"""
from __future__ import annotations

import json
