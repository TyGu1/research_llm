@dataclass
class ICLExample:
    questions: list[str]        # what was transmitted
    original_question: str      # the sensitive question (CUAD template)
    gold: list[str]             # the sensitive values
    context_excerpt: str        # a short excerpt of the contract


@dataclass
class AttackOutput:
    attack: str
    observation: str            # Q | Q+ | S0 | Qxk | DP-text | SUB-text
    reconstruction: str
    extra: dict = field(default_factory=dict)
    prompt_chars: int = 0


