"""
Test 1 (Headline Result): Sensitive Data Recovery from Transmitted Content.

The tested object is the S0 proxy questions — what the cloud actually receives.
The question: can an attacker recover sensitive content from the original S2 prompt
by attacking only what was transmitted?

Comparison: arXiv:2410.12443 shows DP-sanitized text is recoverable at 72-94%.
Our pipeline transmits content from which the sensitive specifics were never encoded.

Three attack variants, three scoring granularities:
  Domain recovery:         did attacker identify the correct CUAD clause category?
  Situation recovery:      semantic sim of attacker reconstruction vs. original context
  Specific value recovery: exact substring match of gold answer spans in attacker output
                           — this is the critical metric; must be near zero.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field

import numpy as np
from sentence_transformers import SentenceTransformer

from src.data.cuad_loader import CUADSample
from src.pipeline.base import PipelineResult


@dataclass
class AttackResult:
    reconstruction: str
    domain_recovered: bool          # attacker identified correct category
    situation_score: float          # semantic similarity [0, 1]
    specific_value_rate: float      # fraction of gold spans found in reconstruction


@dataclass
class RecoveryResult:
    sample_id: str
    direct: AttackResult | None = None
    icl: AttackResult | None = None
    expert: AttackResult | None = None
    absence_fingerprint: AttackResult | None = None

    @property
    def mean_specific_value_rate(self) -> float:
        rates = [
            r.specific_value_rate
            for r in [self.direct, self.icl, self.expert, self.absence_fingerprint]
            if r is not None
        ]
        return float(np.mean(rates)) if rates else 0.0


class SensitiveRecoveryEvaluator:
    DIRECT_SYSTEM = "You are a security researcher reconstructing the original sensitive document from derived questions."
    ICL_SYSTEM = "You are an expert at reverse-engineering the source of anonymized questions."
    EXPERT_SYSTEM = "You are a senior contract lawyer and security expert."

    DIRECT_PROMPT = """The following questions were generated by a privacy system from a confidential contract clause.
What was the original sensitive contract clause or question they were derived from?
Reconstruct it as specifically as possible, including any entity names, values, or dates.

Questions:
{questions}

Reconstruction:"""

    ICL_PROMPT = """Examples of how a privacy system transforms sensitive contract questions:

{examples}

Now reconstruct the original sensitive contract information from these questions:
{questions}

Reconstruction:"""

    EXPERT_PROMPT = """You are a senior M&A lawyer reviewing anonymized research questions.
Based on these questions, what specific contract clause, parties, and terms are they investigating?
Include any specific company names, dollar amounts, or dates you can infer.

Questions:
{questions}

Most likely original contract information:"""

    ABSENCE_SYSTEM = "You are a security researcher analyzing information leakage through vocabulary exclusion patterns."

    ABSENCE_PROMPT = """A privacy system processed a confidential contract by:
1. Extracting a topic distribution from the original sensitive text
2. Generating generic text about those topics
3. Stripping certain vocabulary words from the generated text

You have access to:
- The topic distribution: {topics}
- The text after vocabulary exclusion: {s0_text}

Identify which specific terms, entity names, dollar amounts, or dates were likely excluded
from this text. Then reconstruct the original sensitive contract clause as specifically as
possible.

Reconstructed original sensitive information:"""

    def __init__(
        self,
        attacker_client,
        embed_model: SentenceTransformer,
        icl_examples: list[tuple[str, list[str]]] | None = None,
    ):
        self._client = attacker_client
        self._embed_model = embed_model
        self._icl_examples = icl_examples or []   # (original_context, proxy_questions)

    def _format_questions(self, questions: list[str]) -> str:
        return "\n".join(f"- {q}" for q in questions)

    def _score(
        self,
        reconstruction: str,
        sample: CUADSample,
    ) -> tuple[bool, float, float]:
        # Domain recovery: does reconstruction mention the category?
        category_words = sample.category.lower().replace("-", " ").split()
        domain_recovered = any(w in reconstruction.lower() for w in category_words if len(w) > 3)

        # Situation recovery: semantic similarity vs. original context excerpt
        ctx_excerpt = sample.context[:500]
        embs = self._embed_model.encode([reconstruction, ctx_excerpt])
        situation_score = float(
            np.dot(embs[0], embs[1]) / (np.linalg.norm(embs[0]) * np.linalg.norm(embs[1]) + 1e-9)
        )

        # Specific value recovery: fraction of gold spans found as substrings
        if not sample.answers:
            specific_value_rate = 0.0
        else:
            found = sum(
                1 for ans in sample.answers
                if ans.lower()[:50] in reconstruction.lower()
            )
            specific_value_rate = found / len(sample.answers)

        return domain_recovered, max(0.0, situation_score), specific_value_rate

    def _attack(self, prompt: str, system: str, questions: list[str], sample: CUADSample) -> AttackResult:
        reconstruction = self._client.generate(prompt, system=system)
        domain, situation, specific = self._score(reconstruction, sample)
        return AttackResult(
            reconstruction=reconstruction,
            domain_recovered=domain,
            situation_score=situation,
            specific_value_rate=specific,
        )

    def evaluate(self, sample: CUADSample, result: PipelineResult) -> RecoveryResult:
        questions = result.selected_questions
        if not questions:
            return RecoveryResult(sample_id=sample.id)

        q_str = self._format_questions(questions)
        recovery = RecoveryResult(sample_id=sample.id)

        # Attack 1: Direct recovery
        recovery.direct = self._attack(
            self.DIRECT_PROMPT.format(questions=q_str),
            self.DIRECT_SYSTEM,
            questions,
            sample,
        )

        # Attack 2: In-context learning (if examples available)
        if self._icl_examples:
            examples_str = "\n\n".join(
                f"Original: {ctx[:200]}\nQuestions:\n" + "\n".join(f"- {q}" for q in qs)
                for ctx, qs in self._icl_examples[:3]
            )
            recovery.icl = self._attack(
                self.ICL_PROMPT.format(examples=examples_str, questions=q_str),
                self.ICL_SYSTEM,
                questions,
                sample,
            )

        # Attack 3: Domain expert
        recovery.expert = self._attack(
            self.EXPERT_PROMPT.format(questions=q_str),
            self.EXPERT_SYSTEM,
            questions,
            sample,
        )

        # Attack 4: Absence fingerprint (only when vocab exclusion was used)
        if result.s0_text_excluded:
            topics_str = json.dumps(result.topics.topics) if result.topics else "{}"
            recovery.absence_fingerprint = self._attack(
                self.ABSENCE_PROMPT.format(topics=topics_str, s0_text=result.s0_text_excluded),
                self.ABSENCE_SYSTEM,
                questions,
                sample,
            )

        return recovery
